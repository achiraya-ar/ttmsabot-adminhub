-- =====================================================================
--  คัดลอกตาราง schedules เดิม → schedule_versions
--  และลบฟีเจอร์ booking_start_date ออก
--
--  หมายเหตุ:
--  - ไฟล์นี้ "ไม่ลบ" ตาราง public.schedules
--  - เว็บไซต์เก่ายังคงใช้งาน schedules ได้ตามปกติ
--  - ข้อมูล schedules เดิมจะถูกคัดลอกมาเป็นเวอร์ชันเริ่มต้น
--    effective_from = 2000-01-01 ใน schedule_versions
--  - เมื่อเว็บไซต์ทุกตัวอัปเดตเป็น schedule_versions แล้ว
--    ค่อยรันคำสั่ง drop table public.schedules แยกต่างหาก
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1) ตารางเวอร์ชันตารางเวลา
-- ---------------------------------------------------------------------
create table if not exists public.schedule_versions (
  id bigint generated by default as identity primary key,
  therapist_name text not null,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  time_slots text[] not null default '{}'::text[],
  visibility text not null default 'public',
  slot_visibility jsonb not null default '{}'::jsonb,
  effective_from date not null,
  created_at timestamptz not null default now()
);

alter table public.schedule_versions
  add column if not exists slot_visibility jsonb not null default '{}'::jsonb;

create unique index if not exists schedule_versions_therapist_day_effective_key
  on public.schedule_versions (therapist_name, day_of_week, effective_from);

create index if not exists schedule_versions_lookup_idx
  on public.schedule_versions (therapist_name, day_of_week, effective_from desc);

alter table public.schedule_versions enable row level security;

grant select on public.schedule_versions to anon, authenticated;
grant insert, update, delete on public.schedule_versions to authenticated;

drop policy if exists "schedule_versions_read" on public.schedule_versions;
create policy "schedule_versions_read"
  on public.schedule_versions
  for select
  to anon, authenticated
  using (true);

drop policy if exists "schedule_versions_manage_adminhub" on public.schedule_versions;
create policy "schedule_versions_manage_adminhub"
  on public.schedule_versions
  for all
  to authenticated
  using (public.has_app_access('adminhub'))
  with check (public.has_app_access('adminhub'));

-- ---------------------------------------------------------------------
-- 2) คัดลอกข้อมูล schedules เดิมมาเป็นเวอร์ชันเริ่มต้น
--    โดยยังคงตาราง schedules เดิมไว้ให้เว็บไซต์เก่าใช้งาน
-- ---------------------------------------------------------------------
do $$
begin
  if to_regclass('public.schedules') is not null then
    execute $sql$
      insert into public.schedule_versions
        (therapist_name, day_of_week, time_slots, visibility, slot_visibility, effective_from)
      select distinct on (btrim(therapist_name), day_of_week)
        btrim(therapist_name) as therapist_name,
        day_of_week,
        coalesce(time_slots, '{}'::text[]) as time_slots,
        coalesce(nullif(btrim(visibility), ''), 'public') as visibility,
        (
          select coalesce(
            jsonb_object_agg(slot_time, coalesce(nullif(btrim(visibility), ''), 'public')),
            '{}'::jsonb
          )
          from (
            select distinct unnest(coalesce(time_slots, '{}'::text[])) as slot_time
          ) as slot_times
        ) as slot_visibility,
        date '2000-01-01' as effective_from
      from public.schedules
      where btrim(therapist_name) <> ''
        and day_of_week between 0 and 6
      order by btrim(therapist_name), day_of_week, id desc
      on conflict (therapist_name, day_of_week, effective_from)
      do update set
        time_slots = excluded.time_slots,
        visibility = excluded.visibility,
        slot_visibility = excluded.slot_visibility
    $sql$;
  end if;
end $$;

-- ---------------------------------------------------------------------
-- 3) ลบฟีเจอร์ booking_start_date ออกทั้งหมด
-- ---------------------------------------------------------------------
delete from public.app_settings
where setting_name = 'booking_start_date';

drop policy if exists "app_settings_booking_start_date_read" on public.app_settings;
drop policy if exists "app_settings_booking_start_date_manage" on public.app_settings;
drop policy if exists "app_settings_booking_start_date_manage_adminhub" on public.app_settings;

commit;

notify pgrst, 'reload schema';
